import gzip
import json
import os
import random
import urllib.request

import pyarrow.parquet as pq

EOS = "<|endoftext|>"
HF = "https://huggingface.co/datasets/"
SOURCES = {
    "stories": (HF + "roneneldan/TinyStories/resolve/main/TinyStoriesV2-GPT4-train.txt", "data/raw/stories.txt"),
    "web": (HF + "HuggingFaceFW/fineweb-edu/resolve/main/sample/10BT/000_00000.parquet", "data/raw/fineweb.parquet"),
    "code": (HF + "codeparrot/codeparrot-clean/resolve/main/file-000000000001.json.gz", "data/raw/code.json.gz"),
}
CHARACTERS = {"stories": 300_000_000, "web": 700_000_000, "code": 500_000_000}


def download(name):
    url, path = SOURCES[name]
    if os.path.exists(path):
        return
    print(f"downloading {url}")
    request = urllib.request.Request(url)
    if name == "stories":
        request.add_header("Range", f"bytes=0-{500 * 1024 * 1024 - 1}")
    with urllib.request.urlopen(request) as response, open(path, "wb") as f:
        while chunk := response.read(1 << 20):
            f.write(chunk)


def documents(name):
    path = SOURCES[name][1]
    if name == "stories":
        for story in open(path, encoding="utf-8", errors="ignore").read().split(EOS):
            yield story.strip()
    if name == "web":
        parquet = pq.ParquetFile(path)
        for group in range(parquet.num_row_groups):
            yield from parquet.read_row_group(group, columns=["text"]).column("text").to_pylist()
    if name == "code":
        for line in gzip.open(path, "rt", encoding="utf-8"):
            row = json.loads(line)
            if not row["autogenerated"] and len(row["content"]) < 100_000:
                yield row["content"]


def take(name):
    docs, total = [], 0
    for doc in documents(name):
        if doc:
            docs.append(doc)
            total += len(doc)
        if total >= CHARACTERS[name]:
            break
    return docs


def write(path, docs):
    with open(path, "w") as f:
        for doc in docs:
            f.write(doc + "\n" + EOS + "\n")


if __name__ == "__main__":
    os.makedirs("data/raw", exist_ok=True)
    train = []
    for name in SOURCES:
        download(name)
        docs = take(name)
        random.Random(0).shuffle(docs)
        n_val = len(docs) // 100
        write(f"data/val_{name}.txt", docs[:n_val])
        train += docs[n_val:]
        print(f"{name:8} {len(docs):>9,} documents, {sum(map(len, docs)):>13,} characters")
    random.Random(0).shuffle(train)
    write("data/train.txt", train)
    print(f"data/train.txt: {len(train):,} documents")
